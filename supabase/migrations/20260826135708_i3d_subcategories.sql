create or replace function private.validate_subcategory_category()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_category_active boolean;
begin
    select c.is_active
      into v_category_active
      from public.categories c
     where c.id = new.category_id;

    if not found then
        raise exception using
            errcode = '23503',
            message = 'A categoria da subcategoria não existe.';
    end if;

    if new.is_active and v_category_active is not true then
        raise exception using
            errcode = '23514',
            message = 'Subcategorias ativas devem pertencer a uma categoria ativa.';
    end if;

    return new;
end;
$$;

