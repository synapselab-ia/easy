create or replace function private.validate_item_subcategory()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_subcategory_active boolean;
begin
    if new.subcategory_id is null then
        return new;
    end if;

    select s.is_active
      into v_subcategory_active
      from public.subcategories s
     where s.id = new.subcategory_id
       and s.category_id = new.category_id;

    if not found then
        raise exception using
            errcode = '23514',
            message = 'A subcategoria selecionada deve pertencer à categoria do item.';
    end if;

    if new.is_active and v_subcategory_active is not true then
        raise exception using
            errcode = '23514',
            message = 'Itens ativos não podem usar uma subcategoria arquivada.';
    end if;

    return new;
end;
$$;

