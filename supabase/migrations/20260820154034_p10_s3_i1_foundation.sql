create or replace function private.validate_item_category()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_category_active boolean;
    v_must_validate boolean := false;
begin
    if new.is_active and new.category_id is null then
        raise exception using
            errcode = '23514',
            message = 'Itens ativos devem possuir uma categoria ativa.';
    end if;

    if new.category_id is not null then
        if tg_op = 'INSERT' then
            v_must_validate := true;
        elsif old.category_id is distinct from new.category_id
           or (not old.is_active and new.is_active)
        then
            v_must_validate := true;
        end if;
    end if;

    if v_must_validate then
        select c.is_active
          into v_category_active
          from public.categories c
         where c.id = new.category_id;

        if not found or v_category_active is not true then
            raise exception using
                errcode = '23514',
                message = 'A categoria selecionada deve existir e estar ativa.';
        end if;
    end if;

    return new;
end;
$$;

create trigger items_validate_category
before insert or update on public.items
for each row execute function private.validate_item_category();

create or replace function private.guard_category_archive()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if old.is_active and not new.is_active
       and exists (
            select 1
              from public.items i
             where i.category_id = old.id
               and i.is_active
       )
    then
        raise exception using
            errcode = '23514',
            message = 'Categorias usadas por itens ativos não podem ser arquivadas.';
    end if;

    return new;
end;
$$;

create trigger categories_guard_archive
before update of is_active on public.categories
for each row execute function private.guard_category_archive();

create or replace function public.is_easy_operator()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
    select
        (select auth.uid()) is not null
        and exists (
            select 1
              from public.easy_operators eo
             where eo.user_id = (select auth.uid())
               and eo.is_active
        );
$$;

create or replace function private.assert_easy_operator()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if (select auth.uid()) is null
       or not exists (
            select 1
              from public.easy_operators eo
             where eo.user_id = (select auth.uid())
               and eo.is_active
       )
    then
        raise exception using
            errcode = '42501',
            message = 'Usuário não autorizado para operar o Easy.';
    end if;
end;
$$;

