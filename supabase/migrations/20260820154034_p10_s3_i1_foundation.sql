    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint resellers_name_not_blank check (btrim(name) <> '')
);

create table public.transactions (
    id bigint generated by default as identity primary key,
    reseller_id bigint not null references public.resellers(id) on update restrict on delete restrict,
    type text not null,
    item_id bigint null references public.items(id) on update restrict on delete restrict,
    item_name text null,
    quantity integer null,
    unit_price numeric null,
    category_id bigint null references public.categories(id) on update restrict on delete restrict,
    category_name text null,
    total_price numeric not null,
    observation text null,
    reversal_reason text null,
    reversed_at timestamptz null,
    replacement_transaction_id bigint null,
    replaces_transaction_id bigint null,
    occurred_at timestamptz not null,
    created_at timestamptz not null default now(),
    constraint transactions_type_valid check (type in ('order', 'payment', 'signal')),
    constraint transactions_order_shape_valid check (
        (
            type = 'order'
            and item_id is not null
            and item_name is not null
            and btrim(item_name) <> ''
            and quantity is not null
            and quantity > 0
            and unit_price is not null
            and unit_price >= 0
            and total_price = quantity * unit_price
            and (
                (category_id is null and category_name is null)
                or (category_id is not null and category_name is not null and btrim(category_name) <> '')
            )
        )
        or
        (
            type in ('payment', 'signal')
            and item_id is null
            and item_name is null
            and quantity is null
            and unit_price is null
            and category_id is null
            and category_name is null
            and total_price > 0
        )
    ),
    constraint transactions_reversal_shape_valid check (
        (
            reversal_reason is null
            and reversed_at is null
            and replacement_transaction_id is null
        )
        or
        (
            reversal_reason is not null
            and btrim(reversal_reason) <> ''
            and reversed_at is not null
        )
    ),
    constraint transactions_replacement_not_self check (
        replacement_transaction_id is null or replacement_transaction_id <> id
    ),
    constraint transactions_replaces_not_self check (
        replaces_transaction_id is null or replaces_transaction_id <> id
    ),
    constraint transactions_replacement_transaction_unique unique (replacement_transaction_id),
    constraint transactions_replaces_transaction_unique unique (replaces_transaction_id)
);

